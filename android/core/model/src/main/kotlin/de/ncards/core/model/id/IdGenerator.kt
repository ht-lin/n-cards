package de.ncards.core.model.id

/**
 * 客户端主键生成器（§4.3 铁律四）。
 *
 * ============================================================================
 * 为什么它住在 `core:model`
 * ============================================================================
 * `core/model/build.gradle.kts` 的文件头早就写好了归属：「§4.3：客户端生成 UUIDv7
 * 作为主键，所以离线创建的实体从一开始就有稳定 ID。**那个生成器将来也住在这里**」。
 * 本卡（T-155）是第一个需要它的人 —— 在此之前全仓只有两处 `UUID.randomUUID()`，
 * 那是 v4，不是 v7。
 *
 * ============================================================================
 * 为什么是接口而不是一个顶层函数
 * ============================================================================
 * 两条，都不是风格问题：
 *
 * - `DefaultCardRepositoryTest` 要断言「建卡写进 Room 的那一行的 id，与写进 outbox
 *   的那条载荷里的 id 是同一个」。一个顶层函数没法在测试里种一个已知值，
 *   那条断言就只能写成「两个都非空」—— 而那正好漏掉了会真的发生的那个 bug
 *   （两处各生成一次）。
 * - `core:model` 是 `ncards.jvm.library`，这里没有 Hilt。绑定在 `data:card` 的
 *   `CardModule` 里 `@Provides`，与它已有的 `DefaultDispatcherProvider()` 同一个形态。
 */
fun interface IdGenerator {
    /** 一个新的 UUIDv7，规范的 36 字符小写连字符形态。 */
    fun newId(): String
}
