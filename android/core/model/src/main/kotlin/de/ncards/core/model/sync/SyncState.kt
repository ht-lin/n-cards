package de.ncards.core.model.sync

/**
 * 一张卡在本机的同步状态（§4.3 铁律三：网络失败不回滚 UI，只更这个并显示细微徽章）。
 *
 * ============================================================================
 * ⚠️ 它是**算出来的**，不是存出来的
 * ============================================================================
 * `cards` 表上**没有** `sync_state` 列。T-009 的落地记录写明了理由：
 * 「一份状态存两处，迟早漂移成两份，而漂移时没人知道该信哪个」。
 * 真相源是 `sync_outbox`，由 `CardDao.observeWallet` 的 `CASE WHEN` 派生。
 *
 * ============================================================================
 * ⚠️ 为什么只有三格，而 §4.3 写了四个
 * ============================================================================
 * §4.3 的原文是 `PENDING` / `SYNCING` / `SYNCED` / `FAILED`。这里没有 `SYNCING`，
 * 因为**今天没有任何东西能产出它**：`observeWallet` 的 SQL 只看 outbox 里有没有
 * 记录、`attempt_count` 到没到上限，而「正在推」是一个只有 SyncEngine 跑起来
 * 才存在的瞬时状态 —— 那是 T-250。
 *
 * 现在就把 `SYNCING` 加上，只会得到一个永远走不到的分支，
 * 以及一批对它恒真的断言（T-109 的 `encryption_scheme` 已经踩过这个坑：
 * 「任何在单元层对它的断言对静态分析都是恒真的」，最后那两条断言被删掉了）。
 *
 * T-250 加第四个常量时，每一个穷举 `when` 都会编译失败并被迫表态 ——
 * 这正是 ADR-0023 选择「枚举常量而非可空」时要的那个性质。
 *
 * @property column `CardDao.observeWallet` 派生出的那一列的字面值，逐字一致。
 */
enum class SyncState(
    val column: String,
) {
    /** outbox 里没有这张卡的记录 —— 本机与服务端一致。**不显示徽章。** */
    SYNCED("SYNCED"),

    /** 有记录，还没到重试上限。显示「待同步」徽章。 */
    PENDING("PENDING"),

    /** `attempt_count` 已到上限（§5.4.3：10 次）。显示「同步失败」徽章。 */
    FAILED("FAILED"),
    ;

    companion object {
        /**
         * 从 `observeWallet` 派生的那一列还原。
         *
         * 认不出来兜底到 [SYNCED]，即**不显示徽章**。这是刻意的保守选择：
         * 徽章是一个「有问题」的信号，凭一个读不懂的字符串就给用户报警，
         * 比什么都不说更糟 —— 而这一列是本仓库自己的 SQL 产出的，
         * 走到兜底分支就说明 SQL 与本枚举漂了，那是 bug，不是数据。
         */
        fun fromColumn(raw: String?): SyncState = entries.firstOrNull { it.column == raw } ?: SYNCED
    }
}
