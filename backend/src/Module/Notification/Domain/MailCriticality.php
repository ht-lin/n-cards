<?php

declare(strict_types=1);

namespace App\Module\Notification\Domain;

/**
 * 一封信在**全局熔断**时的去留（§3.1 / §7.5 最后一行）。
 *
 * ============================================================================
 * 为什么熔断要分级，而不是一刀切
 * ============================================================================
 * §3.1 的原话是「全局日发信量超阈值 → 告警 + **自动熔断非关键邮件（保留 OTP）**」。
 * 括号里那半句是全部意义所在：
 *
 *   - 熔断的目的是**保住发信域名不被拉黑**（R1，影响「致命」——
 *     域名进黑名单等于全站无法登录）。
 *   - 但如果熔断连 OTP 一起掐掉，那它自己就造成了它想避免的后果：
 *     用户登不进去。区别只是「被服务商拉黑」还是「被我们自己拒掉」。
 *
 * 所以分级不是精细化，是让这个机制不自相矛盾的必要条件。
 *
 * ============================================================================
 * 归类的判据：这封信不发，用户会不会卡住
 * ============================================================================
 * `Critical`  收件人**正在等这封信**才能继续（OTP 码、Magic Link）。
 *             不发 = 登录流程当场断掉。任何阈值之上都照发。
 * `Advisory`  收件人**没在等**，信的价值是事后知情（新设备登录提醒、
 *             refresh 重放安全提醒）。丢掉一封的代价是「一次安全事件没有邮件通知」——
 *             真实但可承受，何况 §7.1 规定同一件事**同时**会走推送
 *             （新设备登录 → 向该用户所有既有设备发推送），邮件不是唯一通道。
 *
 * ⚠️ 加新模板时必须显式选一边（{@see MailTemplate::criticality()} 用的是
 * 无 default 分支的 match，漏一个 case 就编译不过）。不要因为「重要」就选
 * Critical —— 判据是「收件人是不是正卡在这封信上」，不是主观重要性。
 */
enum MailCriticality
{
    /** 收件人正在等这封信；熔断期间照发。 */
    case Critical;

    /** 事后知情类；熔断期间丢弃并记 `email_send_total{result="suppressed"}`。 */
    case Advisory;
}
