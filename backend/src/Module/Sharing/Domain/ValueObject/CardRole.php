<?php

declare(strict_types=1);

namespace App\Module\Sharing\Domain\ValueObject;

/**
 * 一个成员在一张卡上的角色（§5.2 的角色权限矩阵，契约的 `CardRole`）。
 *
 * ============================================================================
 * ⚠️ 只有两格，而且 v1.1 是**收缩**过的
 * ============================================================================
 * `editor` 在 v1.1 被删掉了（C5 / C7：「只有 owner 能写卡」「只有一种可授予的
 * 角色」）。那次收缩不是简化，是让 §5.4 的同步协议在共享场景下退化成
 * **单写者多读者** —— 分布式数据同步里最容易做对的一类模型。
 *
 * 所以这是本仓库**唯一**在库层带 CHECK 的枚举列
 * （`CHECK (role IN ('owner','viewer'))`，§17.1 原样）。
 * 对比 `BarcodeFormat` / `color`：那两个是**开放词汇**，§13.6 允许新增枚举值，
 * 写进 CHECK 之后加一个新条码格式就成了一次要停机对齐的迁移。
 * 这一个反过来 —— 任何试图恢复 `editor` 的提案都必须先重读 §3.5 的冲突矩阵，
 * 让它在库层就撞墙是**想要**的效果。
 *
 * ============================================================================
 * `canEdit()` 在这里，不在 Wallet
 * ============================================================================
 * 契约把 `can_edit` 定义成「`my_role` 的便利镜像」，并要求客户端**用它**来 gate
 * 编辑 UI（而不是自己比较角色字符串）。那面镜子放在拥有角色的这个模块里，
 * M3 加角色时就不会出现两处要同步的判断。
 *
 * Wallet 侧因此拿到的是一个算好的 bool（见
 * {@see \App\Module\Sharing\Application\Dto\CardMembership}），
 * 它自己不做任何角色比较 —— `CardBody` 那句「本类不做任何判断」继续为真。
 */
enum CardRole: string
{
    /** 建卡者。不可转让、不可降级（§5.2）；每张卡恒有且仅有一个活跃 owner。 */
    case Owner = 'owner';

    /** 被共享者。除 `placement` 外无任何上行写入（C5）。 */
    case Viewer = 'viewer';

    /**
     * 契约 `Card.can_edit`。
     *
     * ⚠️ 别在调用方写 `$role === CardRole::Owner` —— 那就是这个方法要消灭的
     * 那种散落判断。§5.2 的权限矩阵里「修改 title / barcode_value / 删卡」
     * 三行是同一个答案，它们共用这一处。
     */
    public function canEdit(): bool
    {
        return self::Owner === $this;
    }
}
