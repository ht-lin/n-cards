<?php

declare(strict_types=1);

namespace App\Module\Sharing\Application\Port;

use App\Shared\Domain\Error\DomainException;
use App\Shared\Domain\Identity\Uuid;

/**
 * 调用者**自己**对一张卡的排序与置顶（`PUT /v1/cards/{id}/placement`，§6.2，T-110）。
 *
 * ============================================================================
 * 这是 viewer 唯一的上行写入端点
 * ============================================================================
 * §5.2 的角色权限矩阵里，viewer 只有两项权利：看，和摆放自己钱包里的位置。
 * `sort_order` / `is_pinned` 存在 `card_members` 上而不是 `cards` 上，
 * 正是为了让这件事成立 —— 同一张共享卡，Anna 置顶、Bob 不置顶，互不影响。
 *
 * 所以本方法**不需要**知道调用者是 owner 还是 viewer：它写的永远是
 * `(cardId, userId)` 那一行，而那一行只属于他自己。
 *
 * ============================================================================
 * ⚠️ 不碰 `cards`，不动 `revision`
 * ============================================================================
 * 契约逐字：「**不走 revision 锁**，不需要 `If-Match`，也不会递增卡的
 * `revision` —— 它改的根本不是卡本身。」
 *
 * 这在本接口这一侧是结构性成立的：Sharing 看不见 `Card`，想动也动不了。
 *
 * ============================================================================
 * 不需要事务
 * ============================================================================
 * 只有一次写，没有第二张表要同生共死。与
 * {@see CardOwnershipRegistrarInterface} 相反 —— 那个必须在事务内，
 * 这个两者都不要求。两个前置条件互相矛盾，这也是它们是两个接口的理由之一。
 *
 * ============================================================================
 * 鉴权判据就是这次写
 * ============================================================================
 * 「不是活跃成员」在这里变成 `403 not_a_member`，调用方**不需要**先查一次
 * 再写。这不只是省一次查询：分成「先查后写」两步会开出一个 TOCTOU 窗口，
 * 而 M3 的级联撤销（T-303）恰好会在那个窗口里把成员行改掉。
 */
interface CardPlacementWriterInterface
{
    /**
     * @param int $sortOrder 已经过范围校验的 int32（列是 `INTEGER`）。
     *                       校验在 `CardPlacementPayload`，不在这里 ——
     *                       越界是一个 `400`，不是领域不变量违例
     *
     * @throws DomainException `not_a_member`（403）—— 调用者在这张卡上没有
     *                         `left_at IS NULL` 的成员行。契约对这个码的语义是
     *                         「客户端应据此**从本地删除该卡**（说明共享已被撤销）」
     */
    public function updatePlacement(Uuid $cardId, Uuid $userId, int $sortOrder, bool $isPinned): void;
}
