declare(strict_types=1);

namespace App\Module\Identity\Domain\ValueObject;

/**
 * `otp_challenges.purpose`（§5.2）。
 *
 * ============================================================================
 * 一期只有一个取值，为什么还要一个 enum
 * ============================================================================
 * §5.2 把这一列写成「`login`（一期仅此一种）」——括号里那句话就是这个 enum 的理由：
 * 它是**一个预留的维度**，不是一个恒定值。可预见的第二个取值是「敏感操作二次确认」
 * （改邮箱、删账号），那时 `purpose` 决定的是发哪封信、有效期多长、验完给什么权限。
 *
 * 现在把它做成单值 enum 而不是 `string`，代价是零，换来的是：新增取值时
 * `match($purpose)` 的每一处都会因为缺分支而 `\UnhandledMatchError`，
 * 而不是安静地走进 `login` 的分支。
 *
 * 这一列**不加库层 CHECK**（§13.6：新增枚举值是向后兼容变更，不该欠一次迁移）。
 */
enum OtpPurpose: string
{
    /** 邮箱 OTP 登录 / 注册（§6.3.1）。 */
    case Login = 'login';
}
