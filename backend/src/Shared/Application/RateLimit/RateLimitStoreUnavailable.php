<?php

declare(strict_types=1);

namespace App\Shared\Application\RateLimit;

/**
 * 限流存储（Redis）不可达。
 *
 * ============================================================================
 * ⚠️⚠️ 这里 fail-**CLOSED**，与 T-004 的幂等**方向相反**
 * ============================================================================
 * 这不是疏漏，是刻意的不对称。理由见 ADR-0003 的 Consequences，摘要：
 *
 * - 幂等 fail-open（{@see \App\Shared\Application\Idempotency\IdempotencyStoreUnavailable}）
 *   的论证建立在「代价有界」上：§5.4.3 已经给创建类端点提供了更强、且与存储无关的
 *   幂等保证，Redis 只是第二道保险。
 * - 限流**没有**第二道保险。fail-open 等于在 Redis 故障期间关掉 §7.5 的 OTP 轰炸
 *   防线与 §3.8 的 username 枚举防线 —— 那是**安全控制**，不是便利功能。
 *   而且攻击者能主动制造这个窗口（打爆 Redis 内存），于是「故障期间的短暂放松」
 *   会变成一个可按需触发的旁路。
 *
 * ⚠️ **两处代码看起来不一致是正常的。** 请不要顺手「修」成一致 —— 先读 ADR-0003。
 *
 * ============================================================================
 * 唯一的例外：on_store_failure: allow
 * ============================================================================
 * `write_endpoints`（§7.5「全部写接口 user 300/min」）是纯防 DoS 而非安全控制，
 * 对它 fail-closed 等于 Redis 单容器（§14.2，无 HA）一次重启就全站写入 503 ——
 * 正是 ADR-0003 为幂等否决掉的那个后果。所以策略可以在
 * `config/packages/rate_limiter.yaml` 里显式声明 `on_store_failure: allow`。
 *
 * **默认是 `deny`**：不写这一行就是 fail-closed。新增策略时要主动选择放松，
 * 而不是主动记得收紧。
 *
 * ============================================================================
 * fail-closed 时渲染成 503 而不是 429
 * ============================================================================
 * 429 的语义是「我判定你超限了」；这里的真实情况是「我**无法判定**」。
 * 客户端对两者的反应也该不同：429 应该退避到 `Retry-After`，
 * 503 是服务端故障，§5.4.3 的 outbox 会按重试策略处理。
 *
 * 故障不是静默的：`RedisHealthCheck` 会把 `/health/ready` 翻成 503，
 * Caddy / Ansible / §14.3 的部署健康检查都看得到。
 */
final class RateLimitStoreUnavailable extends \RuntimeException
{
}
