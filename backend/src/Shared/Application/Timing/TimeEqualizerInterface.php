<?php

declare(strict_types=1);

namespace App\Shared\Application\Timing;

/**
 * 把一段处理的**总耗时**拉平到一个固定预算 —— §3.8 防账号枚举的时间侧信道防线。
 *
 * ============================================================================
 * 它挡的是什么
 * ============================================================================
 * `POST /v1/auth/otp/request` 对「已注册」与「未注册」的邮箱必须返回**同样的**
 * 响应体、状态码与**耗时**。前两者靠代码结构就能保证，耗时不行：
 * 真实路径要往 `messenger_messages` 插一行（入队 OTP 信），decoy 路径不插。
 * 那一条 INSERT 是几毫秒，但攻击者可以对同一个邮箱重复采样、取中位数 ——
 * 几毫秒的稳定差值在几十次采样后就是一个可靠的「这个邮箱注册过吗」的读数，
 * 而邮箱字典是可批量购买的。
 *
 * 所以调用方先 {@see begin()} 领一个预算，处理完在返回前 {@see TimeBudget::settle()}，
 * 由实现把剩余时间睡掉。两条路径于是都恰好耗掉预算。
 *
 * ============================================================================
 * 为什么不靠「让两条路径做等量的活」
 * ============================================================================
 * 那是**第一道**防线，本仓库也确实做了（`RequestOtpService` 里 decoy 分支那次
 * 被丢弃的 `encrypt()`，就是用来配平真实路径在消息序列化器里那次加密的）。
 * 但它只在「今天这两条路径」上成立：T-104 要加 `attempts++`、T-106 要加
 * magic token，每加一步都要重新配一次平，而配错了**没有任何症状** ——
 * 功能测试全绿，泄露悄悄打开。固定预算是那道防线的兜底，它对新增的不对称免疫。
 *
 * ============================================================================
 * ⚠️ 预算必须大于慢路径的 p99
 * ============================================================================
 * 预算小于实际耗时时 `settle()` 不睡，差值原样暴露 —— 也就是**防线静默失效**。
 * 实现必须在越界时记一行 warning，那是唯一能发现这件事的信号。
 * 取值与校准方法见 `config/packages/ncards_otp.yaml`。
 *
 * ============================================================================
 * 为什么接口在 Shared\Application
 * ============================================================================
 * 与 {@see \App\Shared\Application\Crypto\CryptoServiceInterface} 同一套论证：
 * deptrac 里各模块的 Application 层允许 `Shared.Application`，不允许
 * `Shared.Infrastructure`。而调用方恰恰都在 Application 层（T-103 的
 * `RequestOtpService`，将来 T-104 的 verify、T-106 的 magic consume）。
 */
interface TimeEqualizerInterface
{
    /**
     * 领一个耗时预算，计时从这一刻开始。
     *
     * @param int<1, max> $budgetMillis 总耗时目标，毫秒
     */
    public function begin(int $budgetMillis): TimeBudget;
}
